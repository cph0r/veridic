#!/usr/bin/env node
// OpenAPI vs code. Repo-wide by default; pass seeds (as for scope) or
// --scope <scope.json> to limit it to one feature.

import fs from "node:fs";
import { openGraph } from "../../core/graph.mjs";
import { routeInventory, normRoute } from "../../core/routes.mjs";
import { scope } from "../../core/scope.mjs";
import { findOpenapi, loadContract, drift } from "../../core/contract.mjs";
import { parseArgs, emit, fail, run, writeAll } from "./_cli.mjs";

const usage = 'drift.mjs --repo <path> [--openapi <file>] [--entry <app file>] [--scope <scope.json> | "<METHOD /path>" ...] [--md]';

run(() => {
  const a = parseArgs(process.argv.slice(2), { flags: ["repo", "openapi", "entry", "scope"], bools: ["md"] });
  if (!a.repo) fail("need --repo", usage);
  const openapiFile = a.openapi ?? findOpenapi(a.repo);
  if (!openapiFile) fail("no OpenAPI document found; pass --openapi", usage);
  const g = openGraph(a.repo);
  const inv = routeInventory(g, { entry: a.entry });
  const contract = loadContract(a.repo, openapiFile);

  let routes = inv.routes;
  let scopeIds = null;
  if (a.scope || a._.length) {
    const sc = a.scope ? JSON.parse(fs.readFileSync(a.scope, "utf8")) : scope(g, inv, a._, { openapi: contract.ops });
    if (sc.error) fail(`scope: ${sc.error} (${sc.unresolved?.join(", ")})`, usage);
    scopeIds = new Set([...sc.routes, ...sc.webhooks].map((r) => normRoute(r.id)));
    routes = inv.routes.filter((r) => scopeIds.has(normRoute(r.id)));
  }
  const result = drift(g, contract, routes, { scoped: !!scopeIds, scopeIds });
  if (a.md) {
    writeAll(driftMarkdown(result));
    process.exit(result.summary.problems ? 1 : 0);
  }
  emit({ repo: a.repo, ...(scopeIds ? { scope: [...scopeIds] } : {}), ...result }, result.summary.problems);
}, usage);

/** The contract section of a spec or traceability file, ready to paste. */
function driftMarkdown(r) {
  const out = [`## OpenAPI ↔ implementation (\`${r.openapi}\`)`, ""];
  const s = r.summary;
  out.push(`${s.documented_ops} documented operation(s), ${s.implemented_routes} implemented route(s), ${s.operations_clean} matching cleanly.`, "");
  if (r.documented_not_implemented.length) {
    out.push("**Documented but not implemented**", "", ...r.documented_not_implemented.map((o) => `- \`${o.id}\` (contract: \`${o.contract_at}\`)`), "");
  }
  if (r.implemented_not_documented.length) {
    out.push("**Implemented but not documented**", "", "| Route | Implementation |", "|---|---|", ...r.implemented_not_documented.map((o) => `| \`${o.id}\` | \`${o.at}\` |`), "");
  }
  for (const o of r.operations) {
    out.push(`**\`${o.id}\`** (\`${o.at}\`, contract \`${o.contract_at}\`)`, "");
    for (const u of o.undocumented_statuses ?? []) out.push(`- Returns ${u.status}${u.implicit ? " (implicit)" : ""} at \`${u.at}\`; the contract doesn't document it.`);
    for (const u of o.unreturned_statuses ?? []) out.push(`- Documents ${u.status}, which the handler never returns${u.maybe_from ? ` (may come from ${u.maybe_from.join(", ")})` : ""}.`);
    for (const f of o.undeclared_body_fields ?? []) out.push(`- Reads \`req.body.${f.field}\` at \`${f.at}\`, which the request schema doesn't declare${f.note ? ` (${f.note})` : ""}.`);
    out.push("");
  }
  out.push("_Generated by `veridic drift --md`. Status codes set inside helper functions are not scanned; confirm those by reading._", "");
  return out.join("\n");
}
