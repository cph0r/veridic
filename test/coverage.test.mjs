// Spec coverage: how much of the app the specs describe, per part, with every
// file left out and why.
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { specCoverage, skipReason, coverageMarkdown } from "../core/coverage.mjs";

function repoWith(files) {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), "veridic-cov-"));
  for (const [f, t] of Object.entries(files)) fs.mkdirSync(path.dirname(path.join(repo, f)), { recursive: true }), fs.writeFileSync(path.join(repo, f), t);
  return { repo, files: Object.keys(files), done: () => fs.rmSync(repo, { recursive: true, force: true }) };
}
const spec = (cites) => ({ path: "specs/a/spec.md", requirements: [{ id: "FR-001", requirement: true, cites: cites.map((c) => ({ cite: c, file: c.replace(/:.*$/, "") })) }] });
const CODE = "export function f() {\n  return 1;\n}\n";

test("coverage counts cited behaviour files and lists skips", () => {
  const r = repoWith({
    "src/a.ts": CODE, "src/b.ts": CODE, "src/a.test.ts": CODE, "src/gen/generated/api.ts": CODE,
    "src/types.ts": "export type X = { a: string };\n", "vite.config.ts": CODE, "scripts/seed.ts": CODE,
  });
  const c = specCoverage(r.repo, { specs: [spec(["src/a.ts:1-2"])], modules: [] }, { files: r.files });
  assert.equal(c.behaviour, 2);
  assert.equal(c.covered, 1);
  assert.equal(c.pct, 50);
  assert.deepEqual(c.skipped.map((s) => s.reason), ["seed or script", "test", "generated", "types only", "config or build"]);
  assert.deepEqual(c.orphans, ["src/b.ts"]);
  r.done();
});

test("coverage per part", () => {
  const r = repoWith({ "src/a.ts": CODE, "src/b.ts": CODE });
  const c = specCoverage(r.repo, { specs: [spec(["src/a.ts:1"])], modules: [{ id: "orders", name: "Orders", files: ["src/a.ts"], code: ["src/b.ts"] }] }, { files: r.files });
  const p = c.parts.find((x) => x.id === "orders");
  assert.deepEqual({ kind: p.kind, total: p.total, covered: p.covered, uncovered: p.uncovered }, { kind: "module", total: 2, covered: 1, uncovered: ["src/b.ts"] });
  assert.deepEqual(c.orphans, []);
  assert.match(coverageMarkdown(c), /^Covered: 1 of 2 behaviour files \(50%\)/);
  r.done();
});

test("coverage resolves cited paths like cite does", () => {
  const r = repoWith({ "apps/api/src/x.ts": CODE });
  const c = specCoverage(r.repo, { specs: [spec(["src/x.ts:1"])], modules: [] }, { files: r.files });
  assert.equal(c.covered, 1);
  r.done();
});

test("coverage on a repo with no parts", () => {
  const r = repoWith({ "lib/a.js": CODE, "lib/deep/b.js": CODE });
  const c = specCoverage(r.repo, { specs: [], modules: [] }, { files: r.files });
  assert.equal(c.covered, 0);
  assert.deepEqual(c.orphans.sort(), ["lib/a.js", "lib/deep/b.js"]);
  assert.ok(c.orphanFolders.length >= 1);
  r.done();
});

test("generated banner is read from the first lines only", () => {
  assert.equal(skipReason("src/api.ts", "// @generated by orval\n", () => CODE), "generated");
  const late = Array(49).fill("// x").join("\n") + "\n// do not edit\n" + CODE;
  assert.equal(skipReason("src/late.ts", late.split("\n").slice(0, 10).join("\n"), () => late), null);
});

// ---- final review fixes ----
test("final: a 'do not edit' comment after code is not a generated banner; enums and default objects are behaviour; seed- isn't a seed", () => {
  assert.equal(skipReason("src/status.ts", 'import x from "y";\n// Do not edit the status order below without updating the DB enum\n', () => CODE), null);
  assert.equal(skipReason("src/gen.ts", "/* eslint-disable */\n// @generated by orval\n", () => CODE), "generated");
  assert.equal(skipReason("src/status.ts", "", () => "export enum OrderStatus { Open, Closed }\n"), null);
  assert.equal(skipReason("src/route.ts", "", () => 'export default { path: "/x", handler: a };\n'), null);
  assert.equal(skipReason("src/api/seed-handler.ts", "", () => CODE), null);
  assert.equal(skipReason("src/viteHelpers.ts", "", () => CODE), null);
  assert.equal(skipReason("db/seeds/users.ts", "", () => CODE), "seed or script");
  assert.equal(skipReason("db/seed.ts", "", () => CODE), "seed or script");
});

test("final: vendored, minified and built files are skipped, and a huge file is not read whole", () => {
  assert.equal(skipReason("public/vendor/jquery.min.js", "", () => CODE), "vendored or built");
  assert.equal(skipReason("dist/app.js", "", () => CODE), "vendored or built");
  let read = 0;
  assert.equal(skipReason("src/big.ts", "", () => { read++; return "x".repeat(400_000); }), null, "a file too big to be types only is behaviour");
  assert.ok(read <= 1);
});
